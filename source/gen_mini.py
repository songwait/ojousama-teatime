#!/usr/bin/env python3
"""The two pixel avatars for the chat decorations (beside messages, above the prompt), drawn as vector
paths (the desktop app drops embedded pictures).

usage: gen_mini.py <source dir> <out.js> [<preview dir>]
"""
import json
import sys

from PIL import Image

SRC, OUT = sys.argv[1], sys.argv[2]
sys.path.insert(0, SRC)
from pixel_svg import layer  # noqa: E402

OJ = Image.open(f"{SRC}/frames/ojou.png").convert("RGBA")      # 3 frames of 230x340: sway 1, 2, 4
FY = Image.open(f"{SRC}/frames/feiyu3.png").convert("RGBA")    # 3 frames of 145x205: stand, squash, air
OJ_W, FY_W = 230, 145


def pix(im, colours=28, alpha_min=140):
    """RGBA picture -> {(x, y): '#rrggbb'} with few colours (transparent pixels dropped)."""
    rgb = Image.new("RGB", im.size, (0, 0, 0))
    rgb.paste(im, mask=im.getchannel("A"))
    q = rgb.quantize(colors=colours, method=Image.MEDIANCUT, dither=Image.NONE).convert("RGB")
    a = im.getchannel("A").load()
    p = q.load()
    W, H = im.size
    return {(x, y): "#%02x%02x%02x" % p[x, y] for y in range(H) for x in range(W) if a[x, y] >= alpha_min}


def strokes(inner):
    return f'<g transform="translate(0 .5)" fill="none" stroke-width="1.06" shape-rendering="crispEdges">{inner}</g>'


def avatar(im, box, size, ring):
    head = im.crop(box)
    head = head.resize((size, size), Image.LANCZOS)
    bg = f'<circle cx="{size/2}" cy="{size/2}" r="{size/2 - .5}" fill="{ring}"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}">'
            f'<defs><clipPath id="c"><circle cx="{size/2}" cy="{size/2}" r="{size/2 - .5}"/></clipPath></defs>'
            f'{bg}<g clip-path="url(#c)">{strokes(layer(pix(head)))}</g></svg>')


def main():
    # heads: 大小姐 with her flower, 大肥鱼 with her whale hood (boxes in the first HD frame)
    ojou_avatar = avatar(OJ.crop((0, 0, OJ_W, 340)), (52, 18, 192, 158), 40, "#fbe3d3")
    feiyu_avatar = avatar(FY.crop((0, 0, FY_W, 205)), (14, 0, 124, 110), 40, "#dfe6ff")
    out = {"OJOU_AVATAR": ojou_avatar, "FEIYU_AVATAR": feiyu_avatar}
    js = ["// Generated by source/gen_mini.py: the two avatars for the chat decorations.",
          "// Do not edit by hand; regenerate it instead."]
    dts = []
    for k, v in out.items():
        js.append(f"export const {k} = {json.dumps(v)}")
        dts.append(f"export declare const {k}: string")
        print(k, len(v), "chars")
    open(OUT, "w").write("\n".join(js) + "\n")
    open(OUT.replace(".js", ".d.ts"), "w").write("\n".join(dts) + "\n")
    if len(sys.argv) > 3:                      # optional preview folder
        for k, v in out.items():
            open(f"{sys.argv[3]}/{k}.svg", "w").write(v)


main()
