#!/usr/bin/env python3
"""The backdrop: a still seaside at dusk (night in dark mode) with the two of them, as one vector SVG.

The desktop app draws a backdrop as a still picture (no CSS or SMIL animation runs in it) and drops
embedded images, so this is all paths: a smooth ground taken from the empty-promenade picture, a few
glints, sparkles and petals, and the fine-pixel frames of 大小姐 (200 rows) and 大肥鱼 (94 rows). The
mod moves and sizes the pair by rewriting CAST_VARS (/ojou move, /ojou size).

usage: gen_backdrop.py <out.js> [<preview.svg>]
"""
import json
import random
import sys

from PIL import Image

import parts as P
from pixel_svg import layer

OJOU_ROWS = 200
FRAME_W, FRAME_H = 284, 420     # one frame of frames/hd_ojou_strip.png (locked full-resolution frames)


def ojou_first_frame():
    strip = Image.open(f"{P.SRC}/frames/hd_ojou_strip.png").convert("RGBA")
    w = round(FRAME_W * OJOU_ROWS / FRAME_H)
    im = strip.crop((0, 0, FRAME_W, FRAME_H)).resize((w, OJOU_ROWS), Image.LANCZOS)
    rgb = Image.new("RGB", im.size, (0, 0, 0))
    rgb.paste(im, mask=im.getchannel("A"))
    q = rgb.quantize(colors=56, method=Image.MEDIANCUT, dither=Image.NONE).convert("RGB").load()
    a = im.getchannel("A").load()
    pixels = {(x, y): "#%02x%02x%02x" % q[x, y] for y in range(OJOU_ROWS) for x in range(w) if a[x, y] >= 140}
    return P.pixel_group(P.OJ_X, P.OJ_Y, P.OJ_H, (w, OJOU_ROWS), layer(pixels)), w * P.OJ_H / OJOU_ROWS


def still_petals():
    """Petals caught mid-fall."""
    random.seed(23)
    out = []
    for _ in range(10):
        x0, y0 = random.uniform(500, 1750), random.uniform(-140, 260)
        period, offset = random.randint(50, 80), random.randint(0, 79)
        scale, spin = random.uniform(.7, 1.25), random.choice([-1, 1]) * random.randint(8, 18)
        p = ((23 + offset) % period) / period
        fade = p / .06 if p < .06 else (1 - p) / .12 if p > .88 else 1
        out.append(f'<path transform="translate({x0 - 980 * p:.1f} {y0 + 900 * p:.1f}) rotate({(23 * spin) % 360}) '
                   f'scale({scale:.2f})" opacity="{fade:.2f}" d="M0 -9C5 -4 5 4 0 9C-5 4 -5 -4 0 -9Z" fill="url(#petalG)"/>')
    return "".join(out)


STYLE = '''<style>
.night{display:none}
.glint{fill:#fff4dc}.sp{fill:#ffe1a0}.tw{fill:#fff6ea}
CAST
@media (prefers-color-scheme:dark){.day{display:none}.night{display:inline}.glint{fill:#e8eeff}}
</style>'''


def build():
    random.seed(11)
    empty = Image.open(f"{P.SRC}/sheets/empty1.png").convert("RGB")
    ojou, ojou_w = ojou_first_frame()
    fy_shared, (fy_stand, _), fy_size = P.frames([f"{P.SRC}/pixel/feiyu_{i}.png" for i in (1, 2)])
    fy_w = fy_size[0] * P.FY_H / fy_size[1]
    sparkles = "".join(P.sparkle(x, y, r, "sp day")
                       for x, y, r in [(560, 260, 9), (840, 180, 7), (1240, 150, 8), (420, 420, 6), (960, 340, 6), (1500, 120, 8)])
    return "".join([
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 900" preserveAspectRatio="xMidYMid slice" style="{P.CAST_VARS}">',
        P.DEFS, STYLE.replace("CAST", P.cast_css()),
        P.smooth_bg(empty, "day", "bgD", [(250, 500, 420, "#ffd2a0", .55), (1560, 430, 360, "#f08a4a", .28),
                                          (900, 160, 500, "#e9b6d6", .25), (300, 820, 420, "#5a3a44", .25)]),
        P.smooth_bg(P.night_grade(empty), "night", "bgN", [(250, 500, 360, "#ffe2c8", .28), (1560, 430, 320, "#c06a3a", .2),
                                                           (300, 820, 420, "#0a0a18", .35)]),
        '<circle class="day" cx="258" cy="492" r="150" fill="url(#sunG)"/>',
        '<circle class="night" cx="250" cy="495" r="140" fill="url(#moonG)"/>',
        f'<g class="night">{P.stars()}</g>',
        P.glints(), sparkles, still_petals(),
        '<rect width="1600" height="900" fill="url(#vig)"/>',
        '<g class="castg">',
        f'<ellipse cx="{P.f(P.OJ_X + ojou_w / 2)}" cy="{P.OJ_Y + P.OJ_H - 6}" rx="120" ry="16" fill="url(#shadowG)"/>',
        f'<ellipse cx="{P.f(fy_w / 2 + 6)}" cy="507" rx="78" ry="12" fill="url(#shadowG)"/>',
        '<g class="chars">', ojou,
        P.pixel_group(0, 513 - P.FY_H, P.FY_H, fy_size, fy_shared + fy_stand),
        '</g></g></svg>',
    ])


def main():
    svg = build()
    print(len(svg), "chars (limit 131072)", "OVER" if len(svg) > 131072 else "")
    open(sys.argv[1], "w").write(
        "// Generated by source/gen_backdrop.py: the backdrop, one still vector SVG.\n"
        "// Do not edit by hand; regenerate it instead.\n"
        f"export const BACKDROP = {json.dumps(svg, ensure_ascii=False)}\n")
    open(sys.argv[1].replace(".js", ".d.ts"), "w").write("/** The backdrop's SVG document. */\nexport declare const BACKDROP: string\n")
    if len(sys.argv) > 2:
        open(sys.argv[2], "w").write(svg)


if __name__ == "__main__":
    main()
